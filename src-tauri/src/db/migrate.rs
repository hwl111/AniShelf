use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use sqlx::SqlitePool;

use crate::error::AppError;

static MIGRATOR: sqlx::migrate::Migrator = sqlx::migrate!("./migrations");

pub fn latest_version() -> i64 {
    MIGRATOR
        .iter()
        .map(|migration| migration.version)
        .max()
        .unwrap_or(0)
}

#[derive(Debug)]
pub struct MigrationReport {
    pub applied: usize,
    pub backup: Option<PathBuf>,
    pub current_version: i64,
}

pub async fn run(pool: &SqlitePool, backups_dir: &Path) -> Result<MigrationReport, AppError> {
    let applied_versions = applied_versions(pool).await?;
    let pending: Vec<i64> = MIGRATOR
        .iter()
        .filter(|migration| !applied_versions.contains(&migration.version))
        .map(|migration| migration.version)
        .collect();

    if pending.is_empty() {
        return Ok(MigrationReport {
            applied: 0,
            backup: None,
            current_version: current_version(pool).await?,
        });
    }

    let backup = if has_user_schema(pool).await? {
        Some(backup_database(pool, backups_dir, "pre_migration").await?)
    } else {
        None
    };

    MIGRATOR
        .run(pool)
        .await
        .map_err(|error| AppError::Internal(format!("数据库迁移失败：{error}")))?;

    Ok(MigrationReport {
        applied: pending.len(),
        backup,
        current_version: current_version(pool).await?,
    })
}

pub async fn current_version(pool: &SqlitePool) -> Result<i64, AppError> {
    if !has_migrations_table(pool).await? {
        return Ok(0);
    }

    let version: Option<i64> =
        sqlx::query_scalar("SELECT MAX(version) FROM _sqlx_migrations WHERE success = 1")
            .fetch_one(pool)
            .await?;

    Ok(version.unwrap_or(0))
}

pub async fn backup_database(
    pool: &SqlitePool,
    backups_dir: &Path,
    prefix: &str,
) -> Result<PathBuf, AppError> {
    std::fs::create_dir_all(backups_dir)?;

    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_millis())
        .unwrap_or(0);

    let mut path = backups_dir.join(format!("{prefix}_{timestamp}.sqlite"));
    let mut counter = 1;
    while path.exists() {
        path = backups_dir.join(format!("{prefix}_{timestamp}_{counter}.sqlite"));
        counter += 1;
    }

    let escaped_path = path.to_string_lossy().replace('\'', "''");
    // Path is generated by us and single quotes are escaped; audit before wrapping.
    sqlx::raw_sql(sqlx::AssertSqlSafe(format!("VACUUM INTO '{escaped_path}'")))
        .execute(pool)
        .await?;

    Ok(path)
}

async fn applied_versions(pool: &SqlitePool) -> Result<HashSet<i64>, AppError> {
    if !has_migrations_table(pool).await? {
        return Ok(HashSet::new());
    }

    let versions: Vec<i64> =
        sqlx::query_scalar("SELECT version FROM _sqlx_migrations WHERE success = 1")
            .fetch_all(pool)
            .await?;

    Ok(versions.into_iter().collect())
}

async fn has_migrations_table(pool: &SqlitePool) -> Result<bool, AppError> {
    let count: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = '_sqlx_migrations'",
    )
    .fetch_one(pool)
    .await?;

    Ok(count > 0)
}

async fn has_user_schema(pool: &SqlitePool) -> Result<bool, AppError> {
    let count: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'",
    )
    .fetch_one(pool)
    .await?;

    Ok(count > 0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::db::connect;

    use tempfile::tempdir;

    #[tokio::test]
    async fn migrations_apply_once_and_are_idempotent() {
        let dir = tempdir().expect("tempdir");
        let database_file = dir.path().join("anishelf.sqlite");
        let backups_dir = dir.path().join("backups");
        let pool = connect(&database_file).await.expect("connect");

        let first = run(&pool, &backups_dir).await.expect("first migration run");

        assert!(first.applied >= 1);
        assert!(first.backup.is_none(), "fresh database needs no backup");
        assert!(first.current_version >= 1);

        let second = run(&pool, &backups_dir)
            .await
            .expect("second migration run");

        assert_eq!(second.applied, 0);
        assert!(second.backup.is_none());

        let settings_table: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = 'app_settings'",
        )
        .fetch_one(&pool)
        .await
        .expect("sqlite_master query");

        assert_eq!(settings_table, 1);
    }

    #[tokio::test]
    async fn existing_database_is_backed_up_before_migrating() {
        let dir = tempdir().expect("tempdir");
        let database_file = dir.path().join("anishelf.sqlite");
        let backups_dir = dir.path().join("backups");
        let pool = connect(&database_file).await.expect("connect");

        sqlx::query("CREATE TABLE legacy_data (id INTEGER PRIMARY KEY)")
            .execute(&pool)
            .await
            .expect("create legacy table");

        let report = run(&pool, &backups_dir).await.expect("migration run");

        let backup_path = report.backup.expect("backup must be created");
        assert!(backup_path.exists());

        let backup_pool = connect(&backup_path).await.expect("open backup");
        let legacy_table: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = 'legacy_data'",
        )
        .fetch_one(&backup_pool)
        .await
        .expect("backup query");

        assert_eq!(legacy_table, 1);
    }

    #[tokio::test]
    async fn upgrades_partially_migrated_database_with_backup() {
        let dir = tempdir().expect("tempdir");
        let database_file = dir.path().join("anishelf.sqlite");
        let backups_dir = dir.path().join("backups");
        let pool = connect(&database_file).await.expect("connect");

        let partial = sqlx::migrate::Migrator {
            migrations: std::borrow::Cow::Owned(MIGRATOR.iter().take(1).cloned().collect()),
            ..sqlx::migrate::Migrator::DEFAULT
        };
        partial.run(&pool).await.expect("partial migration");

        sqlx::query("INSERT INTO app_settings (key, value_json, updated_at) VALUES ('theme', '\"dark\"', 1)")
            .execute(&pool)
            .await
            .expect("insert setting");

        let report = run(&pool, &backups_dir).await.expect("upgrade run");

        assert_eq!(report.applied, MIGRATOR.iter().count() - 1);
        assert!(report.backup.is_some());

        let setting_count: i64 = sqlx::query_scalar("SELECT COUNT(*) FROM app_settings")
            .fetch_one(&pool)
            .await
            .expect("settings count");
        assert_eq!(setting_count, 1);
    }
}
